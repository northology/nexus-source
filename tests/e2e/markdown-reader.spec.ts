import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { expect, test, type Page } from '@playwright/test';
import { buildDir, guarded, urlFor } from './fixtures';

// Nothing in this file reaches the network: a request to any host but the local server is aborted.
test.beforeEach(async ({ page }) => {
  await page.route((url) => url.hostname !== '127.0.0.1' && url.hostname !== 'localhost', (route) => route.abort());
});

const note = (name: string, text: string) => {
  const file = join(buildDir('live'), 'notes', name);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
};

test.describe('HTML comments', () => {
  test('the Repo reader shows a comment dimmed and labelled, never as markup', async ({ page }) => {
    await page.goto(urlFor('repo', '#/repo/instructions'));
    await page.locator('.repo-item', { hasText: 'Relay' }).click();
    const md = page.locator('.repo-reader .md');
    await expect(md).toContainText('Work in small steps.');
    const comment = md.locator('.md-comment');
    await expect(comment).toHaveCount(1);
    await expect(comment.locator('.md-comment-label')).toHaveText('comment');
    await expect(comment).toContainText('generated by nexus from docs/relay.md · edit the source, not this file');
    expect(await md.innerText()).not.toContain('<!--');
    expect(await md.innerText()).not.toContain('-->');
  });

  test('a build document hides a comment and leaves nothing of it in the page', async ({ page }) => {
    note('comments.md', '# Comments\n\nBefore.\n\n<!-- nexus:start -->\n\nInline <!-- secret inline note --> text.\n\n<!-- secret block note\nover two lines -->\n\nAfter.\n\n```\n<!-- kept in code -->\n```\n');
    await page.goto(urlFor('live', '#/documents/notes?doc=notes/comments.md'));
    const reader = page.locator('.reader');
    await expect(reader.locator('h1')).toHaveText('Comments');
    await expect(reader).toContainText('After.');
    const html = await page.content();
    expect(html).not.toContain('nexus:start');
    expect(html).not.toContain('secret');
    await expect(reader.locator('.md-comment')).toHaveCount(0);
    await expect(reader.locator('pre')).toContainText('<!-- kept in code -->');
  });

  test("Build > Guardrails shows a static rule's comment dimmed and labelled", async ({ page }) => {
    await page.route('**/api/rules/0', (route) =>
      route.fulfill({ status: 200, contentType: 'text/plain', body: '# Working rules\n\n<!-- generated by nexus · edit the source -->\n\nStage explicit paths.\n' }),
    );
    await page.goto(urlFor('planning', '#/logs/guardrails'));
    const rules = page.getByRole('region', { name: 'Static rules' });
    await expect(rules).toContainText('Stage explicit paths.');
    await expect(rules.locator('.md-comment .md-comment-label')).toHaveText('comment');
    await expect(rules.locator('.md-comment')).toContainText('generated by nexus · edit the source');
    expect(await rules.innerText()).not.toContain('<!--');
  });
});

const TOKEN = 'x'.repeat(300);
const URL_TOKEN = `https://example.invalid/${'a1b2c3d4'.repeat(40)}`;
const LONG = `# Long tokens\n\nA paragraph with ${TOKEN} inside it, and \`${TOKEN}\` as code, and ${URL_TOKEN} as a path.\n\n- A list item ${TOKEN}\n\n## ${TOKEN}\n\n| a | b |\n| - | - |\n| ${TOKEN} | \`${TOKEN}\` |\n\n\`\`\`\n${TOKEN}\n\`\`\`\n`;
const SHORT = '# Long tokens\n\nA paragraph with a short word inside it.\n';

/**
 * The page's scroll width must not grow with the long tokens, and the reader must end inside the window. At 390px the
 * top bar's theme switch already ends 24px past the window with short text (a phase-1 shell matter, outside this fix),
 * so the page's scroll width is held to the short page's, not to the window's.
 */
async function measure(page: Page, readerSelector: string) {
  return page.evaluate((sel) => {
    const el = document.querySelector(sel);
    const de = document.documentElement;
    // Prose that runs past the reader's own edge: anything outside a code block that ends beyond the Markdown box.
    const md = el?.querySelector('.md');
    const edge = md ? md.getBoundingClientRect().right : 0;
    const past = md ? Array.from(md.querySelectorAll('*')).filter((n) => !n.closest('pre, .md-mermaid') && n.getBoundingClientRect().right > edge + 1).map((n) => n.tagName) : [];
    const pre = md?.querySelector('pre');
    return { past, pre: pre ? { scroll: pre.scrollWidth, client: pre.clientWidth } : null, scroll: de.scrollWidth, client: de.clientWidth, reader: el ? el.getBoundingClientRect().width : -1, right: el ? el.getBoundingClientRect().right : -1 };
  }, readerSelector);
}

for (const width of [1280, 390]) {
  test.describe(`long unbroken strings at ${width}px`, () => {
    test.use({ viewport: { width, height: 900 } });

    test('a Repo item wraps them and the page never scrolls sideways', async ({ page }) => {
      let text = SHORT;
      await page.route(
        /\/api\/repo\/items\/[0-9a-f]+$/,
        guarded(async (route) => {
          const res = await route.fetch();
          const body = (await res.json()) as { item: unknown; text: string };
          await route.fulfill({ response: res, json: { ...body, text } });
        }),
      );
      await page.goto(urlFor('repo', '#/repo/instructions'));
      await page.locator('.repo-item', { hasText: 'Relay' }).click();
      await expect(page.locator('.repo-reader .md')).toContainText('a short word');
      const before = await measure(page, '.repo-reader');
      text = LONG;
      await page.reload();
      await page.locator('.repo-item', { hasText: 'Relay' }).click();
      await expect(page.locator('.repo-reader .md')).toContainText(TOKEN.slice(0, 50));
      const after = await measure(page, '.repo-reader');
      expect(after.scroll).toBeLessThanOrEqual(width >= 1280 ? after.client : Math.max(after.client, before.scroll));
      // The code block keeps its own sideways scroll, and the page is not widened by it.
      expect(after.pre).not.toBeNull();
      expect(after.pre!.scroll).toBeGreaterThan(after.pre!.client);
      expect(after.right).toBeLessThanOrEqual(after.client);
      expect(after.past).toEqual([]);
      expect(after.reader).toBeLessThanOrEqual(before.reader + 1);
    });

    test('a build document wraps them and the page never scrolls sideways', async ({ page }) => {
      note(`wrap-short-${width}.md`, SHORT);
      note(`wrap-long-${width}.md`, LONG);
      await page.goto(urlFor('live', `#/documents/notes?doc=notes/wrap-short-${width}.md`));
      await expect(page.locator('.reader')).toContainText('a short word');
      const before = await measure(page, '.reader');
      await page.goto(urlFor('live', `#/documents/notes?doc=notes/wrap-long-${width}.md`));
      await expect(page.locator('.reader h1')).toHaveText('Long tokens');
      await expect(page.locator('.reader')).toContainText(TOKEN.slice(0, 50));
      const after = await measure(page, '.reader');
      expect(after.scroll).toBeLessThanOrEqual(width >= 1280 ? after.client : Math.max(after.client, before.scroll));
      // The code block keeps its own sideways scroll, and the page is not widened by it.
      expect(after.pre).not.toBeNull();
      expect(after.pre!.scroll).toBeGreaterThan(after.pre!.client);
      expect(after.right).toBeLessThanOrEqual(after.client);
      expect(after.past).toEqual([]);
      expect(after.reader).toBeLessThanOrEqual(before.reader + 1);
    });
  });
}
