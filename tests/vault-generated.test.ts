import { describe, it, expect } from 'vitest';
import { checkVault } from '../core/vault/check.ts';
import { readMarker, withMarker, sha256 } from '../core/vault/generated.ts';
import { note, vaultRepo } from './vault-helpers.ts';

const golden = (r: ReturnType<typeof checkVault>) => r.findings.map(({ rule, level, file, line }) => ({ rule, level, file, line }));
const hub = (body: string) => withMarker(`---\nclass: hub\ncomponent: api\n---\n# api\n\n${body}`, 'the vault');
const BRIEFING =
  '---\nclass: class\nname: briefing\ndivision: superpowers\nfolder: superpowers/archive\nproduced: authored\nthing: false\nstatuses: []\narchive: []\nrequired: [build]\noptional: []\n---\n# briefing\n';

describe('generated markers', () => {
  it('puts the marker after the frontmatter and hashes everything else', () => {
    const text = withMarker('---\nclass: hub\n---\n# A\n', 'the vault');
    expect(text.split('\n')[3]).toMatch(/^<!-- generated by nexus from the vault · sha256:[0-9a-f]{64} · edit the source, not this file -->$/);
    expect(readMarker(text)).toMatchObject({ source: 'the vault', line: 4 });
    const m = readMarker(text);
    expect(m?.hash).toBe(m?.actual);
    expect(m?.hash).toBe(sha256('---\nclass: hub\n---\n# A\n'));
  });
  it('puts it first when there is no frontmatter', () => {
    expect(withMarker('# Rule\n', 'docs/governance/rules/a.md').split('\n')[0]).toMatch(/^<!-- generated by nexus from docs\/governance\/rules\/a\.md/);
  });
  it('reads CRLF text as the same hash', () => {
    const text = hub('- [[dev/systems/api/retrieval]]\n');
    const m = readMarker(text.replace(/\n/g, '\r\n'));
    expect(m?.actual).toBe(m?.hash);
  });
  it('returns null without a marker', () => {
    expect(readMarker('# plain\n')).toBeNull();
  });
  it('honours the marker only as the first body line, so a note can quote one', () => {
    const quoted = withMarker('# Hub\n', 'the vault');
    const text = `---\nclass: guide\ncomponent: shared\n---\n# How hubs look\n\n\`\`\`markdown\n${quoted}\`\`\`\n`;
    expect(readMarker(text)).toBeNull();
    expect(checkVault(vaultRepo({ 'docs/documentation/general/hubs.md': text }, 'clean')).findings).toEqual([]);
  });
});

describe('checker: generated-modified', () => {
  it('passes a marked note whose hash matches', () => {
    expect(checkVault(vaultRepo({ 'docs/dev/context/api.md': hub('- [[dev/systems/api/retrieval]]\n') }, 'clean')).findings).toEqual([]);
  });
  it('blocks a marked note edited by hand, on the marker line', () => {
    const edited = hub('- [[dev/systems/api/retrieval]]\n').replace('# api', '# api (mine)');
    expect(golden(checkVault(vaultRepo({ 'docs/dev/context/api.md': edited }, 'clean')))).toEqual([
      { rule: 'generated-modified', level: 'block', file: 'docs/dev/context/api.md', line: 5 },
    ]);
  });
});

describe('checker: class-file-name', () => {
  it('blocks a class note whose filename is not its name', () => {
    expect(golden(checkVault(vaultRepo({ 'docs/_meta/classes/brief-two.md': BRIEFING }, 'clean')))).toEqual([
      { rule: 'class-file-name', level: 'block', file: 'docs/_meta/classes/brief-two.md', line: 1 },
    ]);
  });
  it('is kept by --file, like other registry findings', () => {
    const root = vaultRepo({ 'docs/_meta/classes/brief-two.md': BRIEFING }, 'clean');
    expect(checkVault(root, { file: 'docs/design/brand.md' }).findings.map((f) => f.rule)).toEqual(['class-file-name']);
  });
});

describe('checker: archive-build-folder', () => {
  it('blocks an archived note whose build names another folder', () => {
    const r = checkVault(vaultRepo({ 'docs/superpowers/archive/landing-card/plan.md': note({ class: 'plan', component: 'shared', build: 'other-build' }) }, 'clean'));
    expect(golden(r)).toEqual([{ rule: 'archive-build-folder', level: 'block', file: 'docs/superpowers/archive/landing-card/plan.md', line: 4 }]);
  });
  it('blocks an archived note with no build folder at all', () => {
    const r = checkVault(vaultRepo({ 'docs/superpowers/archive/plan.md': note({ class: 'plan', component: 'shared', build: 'landing-card' }) }, 'clean'));
    expect(golden(r)).toEqual([{ rule: 'archive-build-folder', level: 'block', file: 'docs/superpowers/archive/plan.md', line: 2 }]);
  });
});
