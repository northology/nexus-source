import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { applyGenerate, expectedOutputs, planGenerate } from '../core/vault/generate.ts';
import { readMarker, withMarker } from '../core/vault/generated.ts';
import { checkVault } from '../core/vault/check.ts';
import { tempDir } from './helpers.ts';
import { note, vaultRepo } from './vault-helpers.ts';

const META = { 'docs/_meta/components.md': '---\ncomponents: [api, dashboard]\n---\n# Components\n' };
const VAULT = {
  ...META,
  'docs/governance/rules/explicit-staging.md': note({ class: 'rule', component: 'shared', status: 'active', tier: 'always' }, '# Commits stage explicit paths only\n\n**Why:** a stray file once shipped.\n'),
  'docs/governance/rules/merge-loads.md': note({ class: 'rule', component: 'shared', status: 'active', tier: 'scoped', paths: ['data/pipelines/**'] }, '# Every load is an idempotent MERGE\n'),
  'docs/governance/archive/rules/old.md': note({ class: 'rule', component: 'shared', status: 'retired', tier: 'always' }, '# Old\n'),
  'docs/dev/systems/api/retrieval.md': note({ class: 'system', component: 'api', source: 'services/retrieval', uses: '["[[data/datasets/events]]"]' }),
  'docs/data/datasets/events.md': note({ class: 'dataset', component: 'shared', source: 'v_events', feeds: '["[[dev/systems/api/retrieval]]"]' }),
  'docs/data/methods/metrics.md': note({ class: 'method', component: 'dashboard', source: 'app/metrics', uses: '["[[data/datasets/events]]", "[[dev/systems/api/retrieval]]"]' }),
};
const strip = (text: string) => text.split('\n').filter((l) => !l.startsWith('<!-- generated by nexus')).join('\n');

describe('expectedOutputs', () => {
  it('writes one rule file per active rule: scoped rules get paths:, retired ones nothing', () => {
    const out = expectedOutputs(vaultRepo(VAULT));
    expect([...out.keys()].filter((k) => k.startsWith('.claude/'))).toEqual(['.claude/rules/nexus/explicit-staging.md', '.claude/rules/nexus/merge-loads.md']);
    expect(strip(out.get('.claude/rules/nexus/explicit-staging.md') ?? '')).toBe('# Commits stage explicit paths only\n\n**Why:** a stray file once shipped.\n');
    expect(strip(out.get('.claude/rules/nexus/merge-loads.md') ?? '')).toBe('---\npaths:\n  - "data/pipelines/**"\n---\n# Every load is an idempotent MERGE\n');
    expect(readMarker(out.get('.claude/rules/nexus/merge-loads.md') ?? '')?.source).toBe('docs/governance/rules/merge-loads.md');
  });
  it('writes one hub per component with notes, listing them by class, then cross-component uses and feeds', () => {
    const out = expectedOutputs(vaultRepo(VAULT));
    expect(strip(out.get('docs/dev/context/api.md') ?? '')).toBe(
      '---\nclass: hub\ncomponent: api\n---\n# api\n\n## system\n\n- [[dev/systems/api/retrieval]]\n\n## Uses\n\n- [[data/datasets/events]]\n',
    );
    expect(strip(out.get('docs/dev/context/dashboard.md') ?? '')).toBe(
      '---\nclass: hub\ncomponent: dashboard\n---\n# dashboard\n\n## method\n\n- [[data/methods/metrics]]\n\n## Uses\n\n- [[data/datasets/events]]\n- [[dev/systems/api/retrieval]]\n',
    );
    expect(readMarker(out.get('docs/dev/context/api.md') ?? '')?.source).toBe('the vault');
  });
  it('ends a hub with its builds: the records naming its component, then the two repo logs', () => {
    const record = (components: string[]) => note({ class: 'build-record', component: 'shared', build: 'b', components, 'nex-category': 'build-record' }, '# final report\n');
    const out = expectedOutputs(vaultRepo({
      ...VAULT,
      'docs/governance/builds/bravo.md': record(['api', 'dashboard']),
      'docs/governance/builds/alpha.md': record(['api']),
      'docs/governance/decisions.json': '{ "entries": [] }',
      'docs/governance/issues.json': '{ "entries": [] }',
    }));
    const logs = '- [[governance/decisions.json]]\n- [[governance/issues.json]]\n';
    expect(strip(out.get('docs/dev/context/api.md') ?? '')).toBe(
      `---\nclass: hub\ncomponent: api\n---\n# api\n\n## system\n\n- [[dev/systems/api/retrieval]]\n\n## Uses\n\n- [[data/datasets/events]]\n\n## Builds\n\n- [[governance/builds/alpha]]\n- [[governance/builds/bravo]]\n${logs}`,
    );
    expect(strip(out.get('docs/dev/context/dashboard.md') ?? '')).toMatch(new RegExp(`\\n## Builds\\n\\n- \\[\\[governance/builds/bravo\\]\\]\\n${logs.replace(/[[\].]/g, '\\$&')}$`));
  });
  it('lists the builds in the governance hub when no components are listed, and the logs only beside a record', () => {
    const out = expectedOutputs(vaultRepo({
      'docs/governance/builds/alpha.md': note({ class: 'build-record', component: 'shared', build: 'alpha' }, '# final report\n'),
      'docs/governance/decisions.json': '{ "entries": [] }',
    }));
    expect(strip(out.get('docs/dev/context/governance.md') ?? '')).toBe('---\nclass: hub\ncomponent: shared\n---\n# governance\n\n## Builds\n\n- [[governance/builds/alpha]]\n- [[governance/decisions.json]]\n');
    expect(strip(expectedOutputs(vaultRepo({ ...VAULT, 'docs/governance/decisions.json': '{ "entries": [] }' })).get('docs/dev/context/api.md') ?? '')).not.toContain('## Builds');
  });
  it('writes division hubs when no components are listed, and no empty hub', () => {
    const out = expectedOutputs(vaultRepo({ 'docs/design/brand.md': note({ class: 'design-note', component: 'shared' }) }));
    expect([...out.keys()]).toEqual(['docs/dev/context/design.md']);
    expect(strip(out.get('docs/dev/context/design.md') ?? '')).toBe('---\nclass: hub\ncomponent: shared\n---\n# design\n\n## design-note\n\n- [[design/brand]]\n');
  });
  it('writes nothing outside a vault', () => {
    expect(expectedOutputs(tempDir()).size).toBe(0);
  });
});

describe('planGenerate and applyGenerate', () => {
  it('writes everything missing, and the result passes the checker and --check', () => {
    const root = vaultRepo(VAULT);
    const plan = planGenerate(root);
    expect(plan.issues.map((i) => i.kind)).toEqual(['missing', 'missing', 'missing', 'missing']);
    applyGenerate(root, plan);
    expect(planGenerate(root).issues).toEqual([]);
    expect(checkVault(root).findings.filter((f) => f.level === 'block')).toEqual([]);
  });
  it('calls a changed source stale and a hand edit edited, and rewrites both', () => {
    const root = vaultRepo(VAULT);
    applyGenerate(root, planGenerate(root));
    writeFileSync(join(root, 'docs/governance/rules/merge-loads.md'), note({ class: 'rule', component: 'shared', status: 'active', tier: 'scoped', paths: ['data/**'] }, '# Every load MERGEs\n'));
    const hub = join(root, 'docs/dev/context/api.md');
    writeFileSync(hub, readFileSync(hub, 'utf8').replace('# api', '# api!'));
    const plan = planGenerate(root);
    expect(plan.issues).toEqual([{ file: '.claude/rules/nexus/merge-loads.md', kind: 'stale' }, { file: 'docs/dev/context/api.md', kind: 'edited' }]);
    applyGenerate(root, plan);
    expect(planGenerate(root).issues).toEqual([]);
  });
  it('removes a marked file whose source is gone', () => {
    const root = vaultRepo(VAULT);
    mkdirSync(join(root, '.claude/rules/nexus'), { recursive: true });
    writeFileSync(join(root, '.claude/rules/nexus/gone.md'), withMarker('# Gone\n', 'docs/governance/rules/gone.md'));
    const plan = planGenerate(root);
    expect(plan.removes).toEqual(['.claude/rules/nexus/gone.md']);
    expect(plan.issues).toContainEqual({ file: '.claude/rules/nexus/gone.md', kind: 'orphaned' });
    applyGenerate(root, plan);
    expect(existsSync(join(root, '.claude/rules/nexus/gone.md'))).toBe(false);
  });
  it('stops on an unmarked file, writing nothing', () => {
    const root = vaultRepo({ ...VAULT, 'docs/dev/context/api.md': note({ class: 'hub', component: 'api' }, '# hand-made\n') });
    const plan = planGenerate(root);
    expect(plan.issues).toContainEqual({ file: 'docs/dev/context/api.md', kind: 'unmarked' });
    expect(() => applyGenerate(root, plan)).toThrow(/docs\/dev\/context\/api\.md has no generated marker/);
    expect(existsSync(join(root, '.claude/rules/nexus/merge-loads.md'))).toBe(false);
  });
  it('refuses two active rules that would write the same file, naming both, and writes nothing', () => {
    const root = vaultRepo({
      ...VAULT,
      'docs/governance/rules/data/naming.md': note({ class: 'rule', component: 'shared', status: 'active', tier: 'always' }, '# Data names\n'),
      'docs/governance/rules/web/naming.md': note({ class: 'rule', component: 'shared', status: 'active', tier: 'always' }, '# Web names\n'),
    });
    const plan = planGenerate(root);
    expect(plan.issues).toContainEqual({ file: '.claude/rules/nexus/naming.md', kind: 'duplicate' });
    expect(() => applyGenerate(root, plan)).toThrow(/docs\/governance\/rules\/data\/naming\.md and docs\/governance\/rules\/web\/naming\.md both generate \.claude\/rules\/nexus\/naming\.md/);
    expect(existsSync(join(root, '.claude/rules/nexus/merge-loads.md'))).toBe(false);
  });
  it('refuses a scoped rule with no usable paths instead of loading it everywhere', () => {
    const root = vaultRepo({ ...VAULT, 'docs/governance/rules/merge-loads.md': note({ class: 'rule', component: 'shared', status: 'active', tier: 'scoped', paths: 'data' }, '# Every load is an idempotent MERGE\n') });
    const plan = planGenerate(root);
    expect(plan.expected.has('.claude/rules/nexus/merge-loads.md')).toBe(false);
    expect(plan.issues).toContainEqual({ file: 'docs/governance/rules/merge-loads.md', kind: 'invalid' });
    expect(() => applyGenerate(root, plan)).toThrow(/docs\/governance\/rules\/merge-loads\.md is a scoped rule with no paths/);
  });
  it('leaves archived notes and other hubs out of Uses and Feeds', () => {
    const root = vaultRepo({
      ...META,
      'docs/dev/systems/api/retrieval.md': note({ class: 'system', component: 'api', source: 's', uses: '["[[governance/archive/decisions/old]]", "[[dev/context/dashboard]]", "[[data/methods/metrics]]"]' }),
      'docs/governance/archive/decisions/old.md': note({ class: 'decision', component: 'dashboard', status: 'superseded' }),
      'docs/data/methods/metrics.md': note({ class: 'method', component: 'dashboard', source: 'app/metrics' }),
    });
    const out = expectedOutputs(root);
    expect(strip(out.get('docs/dev/context/api.md') ?? '')).toBe('---\nclass: hub\ncomponent: api\n---\n# api\n\n## system\n\n- [[dev/systems/api/retrieval]]\n\n## Uses\n\n- [[data/methods/metrics]]\n');
  });
  it('reads generated files checked out with CRLF as current', () => {
    const root = vaultRepo(VAULT);
    applyGenerate(root, planGenerate(root));
    for (const f of ['.claude/rules/nexus/merge-loads.md', 'docs/dev/context/api.md']) {
      const path = join(root, f);
      writeFileSync(path, readFileSync(path, 'utf8').replace(/\n/g, '\r\n'));
    }
    expect(planGenerate(root).issues).toEqual([]);
    expect(checkVault(root).findings.filter((f) => f.rule === 'generated-modified')).toEqual([]);
  });
});
