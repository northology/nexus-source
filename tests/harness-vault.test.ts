import { describe, it, expect } from 'vitest';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { applyPlan, planInit } from '../core/init/init.ts';
import { RULES_END, RULES_START } from '../core/init/shared.ts';
import type { InitAnswers } from '../core/init/answers.ts';
import type { Fetcher } from '../core/init/obsidian.ts';
import { runInit } from '../core/init/run.ts';
import { applyGenerate, expectedOutputs, planGenerate } from '../core/vault/generate.ts';
import { readMarker } from '../core/vault/generated.ts';
import { governanceInventory } from '../core/governance/inventory.ts';
import { inventoryEnv } from '../core/governance/env.ts';
import { tempDir } from './helpers.ts';
import { note, STANDARD, vaultRepo } from './vault-helpers.ts';

// init and docs generate under Codex and Antigravity (phase-9 Task 9). Antigravity reads .agents/rules/ flat
// (its rules doc), so nexus's rule files sit there with a nexus- prefix; Codex reads no rules folder, so the rules go
// into a generated section inside AGENTS.md's nexus block.

const ANSWERS: InitAnswers = { answers: 1, components: [], tags: [], seeding: [] };
const init = (root: string, harness: 'codex' | 'antigravity') => planInit(root, { standard: STANDARD, answers: ANSWERS, downloads: null, repoName: 'acme', harness });
const block = (harness: 'codex' | 'antigravity') => readFileSync(join(STANDARD, `${harness}-block.md`), 'utf8');
const put = (root: string, rel: string, text: string) => {
  mkdirSync(dirname(join(root, rel)), { recursive: true });
  writeFileSync(join(root, rel), text);
};
const read = (root: string, rel: string) => readFileSync(join(root, rel), 'utf8');

const RULES = {
  'docs/governance/rules/explicit-staging.md': note({ class: 'rule', component: 'shared', status: 'active', tier: 'always' }, '# Commits stage explicit paths only\n\n**Why:** a stray file once shipped.\n'),
  'docs/governance/rules/merge-loads.md': note({ class: 'rule', component: 'shared', status: 'active', tier: 'scoped', paths: ['data/pipelines/**', '*.sql'] }, '# Every load is an idempotent MERGE\n'),
};
const strip = (text: string) => text.split('\n').filter((l) => !l.startsWith('<!-- generated by nexus')).join('\n');

describe('init under Codex and Antigravity', () => {
  for (const harness of ['codex', 'antigravity'] as const) {
    it(`under ${harness} creates AGENTS.md with its block and writes nothing under .claude/`, () => {
      const root = tempDir('nexus-hinit-');
      const plan = init(root, harness);
      expect(plan.problems).toEqual([]);
      expect(plan.actions.filter((a) => a.path.startsWith('.claude/') || a.path === 'CLAUDE.md')).toEqual([]);
      expect(plan.actions.find((a) => a.path === 'AGENTS.md')?.kind).toBe('create');
      applyPlan(root, plan);
      expect(read(root, 'AGENTS.md')).toBe(block(harness));
      expect(existsSync(join(root, '.claude'))).toBe(false);
    });
  }
  it('adds the block once to an AGENTS.md that exists, keeping what it holds', () => {
    const root = tempDir('nexus-hinit-');
    put(root, 'AGENTS.md', '# Mine\n\nKeep this.\n');
    applyPlan(root, init(root, 'antigravity'));
    const text = read(root, 'AGENTS.md');
    expect(text.startsWith('# Mine\n\nKeep this.\n')).toBe(true);
    expect(text.split('<!-- nexus:start -->').length).toBe(2);
  });
  it('treats the same block as present, and a different nexus block as a conflict', () => {
    const same = tempDir('nexus-hinit-');
    put(same, 'AGENTS.md', `# Mine\n\n${block('codex')}`);
    expect(init(same, 'codex').actions.find((a) => a.path === 'AGENTS.md')?.kind).toBe('present');
    const other = tempDir('nexus-hinit-');
    put(other, 'AGENTS.md', '<!-- nexus:start -->\nsomething else\n<!-- nexus:end -->\n');
    expect(init(other, 'codex').problems).toContain('AGENTS.md: already has a nexus block with other content; init leaves it alone');
  });
  it('reads a Codex block whose rules section docs generate has filled as present', () => {
    const root = tempDir('nexus-hinit-');
    put(root, 'AGENTS.md', block('codex').replace(`${RULES_START}\n${RULES_END}`, `${RULES_START}\n<!-- generated by nexus from x · sha256:${'0'.repeat(64)} · edit the source, not this file -->\nrules\n${RULES_END}`));
    expect(init(root, 'codex').actions.find((a) => a.path === 'AGENTS.md')?.kind).toBe('present');
  });
  it('refuses an unmarked nexus- rule file in .agents/rules/ under Antigravity', () => {
    const root = tempDir('nexus-hinit-');
    put(root, '.agents/rules/nexus-mine.md', '# hand-written\n');
    put(root, '.agents/rules/mine.md', '# hand-written, not ours\n');
    expect(init(root, 'antigravity').problems).toEqual(['.agents/rules/nexus-mine.md has no generated marker: .agents/rules/nexus-*.md files are ones nexus generates, so move it first']);
  });
});

describe('init in a repo set up from another harness', () => {
  for (const harness of ['codex', 'antigravity'] as const) {
    it(`under ${harness} adds only its AGENTS.md block, leaving the vault and the answers alone`, () => {
      const root = vaultRepo(RULES);
      const plan = init(root, harness);
      expect(plan.problems).toEqual([]);
      expect(plan.actions.filter((a) => a.kind !== 'present').map((a) => a.path).filter((p) => p.startsWith('docs/') || p.startsWith('.nexus/') || p.startsWith('.claude/'))).toEqual([]);
      expect(plan.actions.find((a) => a.path === 'AGENTS.md')?.kind).toBe('create');
      applyPlan(root, plan);
      expect(read(root, 'AGENTS.md')).toBe(block(harness));
      expect(planGenerate(root, harness).refusals).toEqual([]);
    });
  }
  it('says so when the harness is already added, and changes nothing', () => {
    const root = vaultRepo(RULES);
    put(root, 'AGENTS.md', block('codex'));
    put(root, '.gitignore', '.scratch/\ndocs/.obsidian/workspace*.json\n');
    put(root, '.ignore', 'docs/governance/archive/\ndocs/superpowers/archive/\n');
    expect(init(root, 'codex').problems).toEqual(['this repo is already set up for codex (docs/_meta/ and AGENTS.md\'s nexus block are there)']);
  });
  it('under Claude Code still runs only on a new repo', () => {
    const root = vaultRepo(RULES);
    expect(planInit(root, { standard: STANDARD, answers: ANSWERS, downloads: null, repoName: 'acme', harness: 'claude-code' }).problems).toEqual(['docs/_meta/ already exists: this repo is already set up (init runs once per repo)']);
  });
  it('downloads nothing when it only adds a harness', async () => {
    const root = vaultRepo(RULES);
    const fetcher: Fetcher = () => Promise.reject(new Error('no network here'));
    const r = await runInit(root, { standard: STANDARD, answers: ANSWERS, fetcher, check: false, harness: 'antigravity' });
    expect(r.written).toBe(true);
    expect(read(root, 'AGENTS.md')).toBe(block('antigravity'));
  });
  it("tells a Codex user with no section to run init from Codex", () => {
    const root = vaultRepo(RULES);
    expect(planGenerate(root, 'codex').refusals.join('\n')).toMatch(/run nexus init from Codex/);
  });
});

describe('docs generate under Antigravity', () => {
  it('writes .agents/rules/nexus-<rule>.md with its trigger, each marked with its source note', () => {
    const out = expectedOutputs(vaultRepo(RULES), 'antigravity');
    expect([...out.keys()].filter((k) => !k.startsWith('docs/'))).toEqual(['.agents/rules/nexus-explicit-staging.md', '.agents/rules/nexus-merge-loads.md']);
    expect(strip(out.get('.agents/rules/nexus-explicit-staging.md') ?? '')).toBe('---\ntrigger: always_on\n---\n# Commits stage explicit paths only\n\n**Why:** a stray file once shipped.\n');
    expect(strip(out.get('.agents/rules/nexus-merge-loads.md') ?? '')).toBe('---\ntrigger: glob\nglobs: "data/pipelines/**, *.sql"\n---\n# Every load is an idempotent MERGE\n');
    expect(readMarker(out.get('.agents/rules/nexus-merge-loads.md') ?? '')?.source).toBe('docs/governance/rules/merge-loads.md');
  });
  it("removes its own orphaned file and never touches the user's rules", () => {
    const root = vaultRepo(RULES);
    applyGenerate(root, planGenerate(root, 'antigravity'));
    put(root, '.agents/rules/mine.md', '# mine\n');
    writeFileSync(join(root, 'docs/governance/rules/merge-loads.md'), note({ class: 'rule', component: 'shared', status: 'retired', tier: 'always' }));
    const plan = planGenerate(root, 'antigravity');
    expect(plan.removes).toEqual(['.agents/rules/nexus-merge-loads.md']);
    expect(plan.issues.filter((i) => i.file.includes('mine'))).toEqual([]);
  });
  it('lists its generated rule files in the Repo view as generated, with their source', () => {
    const root = vaultRepo(RULES);
    applyGenerate(root, planGenerate(root, 'antigravity'));
    const env = { ...inventoryEnv({}, process.platform, tempDir('nexus-home-')), ceiling: root };
    const item = governanceInventory(root, env, { harness: 'antigravity' }).items.find((i) => i.location === '.agents/rules/nexus-merge-loads.md');
    expect(item).toMatchObject({ kind: 'generated', scope: 'path-scoped', paths: ['data/pipelines/**', '*.sql'], source: 'docs/governance/rules/merge-loads.md' });
  });
});

describe('docs generate under Codex', () => {
  const codexRepo = () => {
    const root = vaultRepo(RULES);
    put(root, 'AGENTS.md', `# Mine\n\n${block('codex')}\nAfter the block.\n`);
    return root;
  };
  it('fills the rules section inside the nexus block, leaving the rest of AGENTS.md alone', () => {
    const root = codexRepo();
    const before = read(root, 'AGENTS.md');
    const plan = planGenerate(root, 'codex');
    expect(plan.refusals).toEqual([]);
    expect(plan.writes).toContain('AGENTS.md');
    expect([...plan.expected.keys()].filter((k) => !k.startsWith('docs/'))).toEqual([]);
    applyGenerate(root, plan);
    const after = read(root, 'AGENTS.md');
    const at = after.indexOf(RULES_START);
    const end = after.indexOf(RULES_END);
    expect(after.slice(0, at)).toBe(before.slice(0, before.indexOf(RULES_START)));
    expect(after.slice(end)).toBe(before.slice(before.indexOf(RULES_END)));
    const inner = after.slice(at + RULES_START.length + 1, end);
    expect(readMarker(inner)?.source).toBe('docs/governance/rules/');
    expect(inner).toContain('Commits stage explicit paths only');
    expect(inner).toContain('**Why:** a stray file once shipped.');
    expect(inner).toContain('`docs/governance/rules/merge-loads.md`');
    // Each rule inlined in full names its own source note (generated-marked-generated), not just the folder.
    expect(inner).toContain('Generated from `docs/governance/rules/explicit-staging.md`.');
    expect(inner).toContain('`data/pipelines/**`');
    expect(inner).not.toContain('Every load is an idempotent MERGE\n\n');
    expect(existsSync(join(root, '.claude'))).toBe(false);
    expect(planGenerate(root, 'codex').writes).toEqual([]);
  });
  it('calls a hand edit in the section edited, and section text with no marker unmarked', () => {
    const root = codexRepo();
    applyGenerate(root, planGenerate(root, 'codex'));
    writeFileSync(join(root, 'AGENTS.md'), read(root, 'AGENTS.md').replace('a stray file once shipped', 'edited'));
    expect(planGenerate(root, 'codex').issues).toContainEqual({ file: 'AGENTS.md', kind: 'edited' });
    writeFileSync(join(root, 'AGENTS.md'), `${RULES_START}\nmine\n${RULES_END}\n`.replace(/^/, '<!-- nexus:start -->\n') + '<!-- nexus:end -->\n');
    const plan = planGenerate(root, 'codex');
    expect(plan.issues).toContainEqual({ file: 'AGENTS.md', kind: 'unmarked' });
    expect(() => applyGenerate(root, plan)).toThrow(/no generated marker/);
  });
  for (const marker of ['<!-- nexus:start -->', '<!-- nexus:end -->', RULES_START, RULES_END]) {
    it(`refuses a rule that quotes ${marker}, which would cut the section short, and leaves AGENTS.md alone`, () => {
      const root = codexRepo();
      put(root, 'docs/governance/rules/markers.md', note({ class: 'rule', component: 'shared', status: 'active', tier: 'always' }, `# Markers\n\nNever edit inside \`${marker}\`.\n`));
      const before = read(root, 'AGENTS.md');
      const plan = planGenerate(root, 'codex');
      expect(plan.refusals.join('\n')).toContain('docs/governance/rules/markers.md quotes a nexus block marker');
      expect(plan.issues).toContainEqual({ file: 'docs/governance/rules/markers.md', kind: 'invalid' });
      expect(() => applyGenerate(root, plan)).toThrow(/quotes a nexus block marker/);
      expect(read(root, 'AGENTS.md')).toBe(before);
    });
  }
  it('stops on a section that already holds a nexus marker, rather than splicing around it', () => {
    const root = codexRepo();
    applyGenerate(root, planGenerate(root, 'codex'));
    const text = read(root, 'AGENTS.md');
    writeFileSync(join(root, 'AGENTS.md'), text.replace('### Standing rules', `### Standing rules\n\n${RULES_END} by hand`));
    const plan = planGenerate(root, 'codex');
    expect(plan.refusals.join('\n')).toMatch(/AGENTS\.md's nexus rules section holds a nexus marker/);
    expect(() => applyGenerate(root, plan)).toThrow();
  });
  it('refuses when AGENTS.md has no rules section, naming nexus init', () => {
    const root = vaultRepo(RULES);
    put(root, 'AGENTS.md', '# Mine\n');
    const plan = planGenerate(root, 'codex');
    expect(plan.refusals.join('\n')).toMatch(/nexus init/);
    expect(() => applyGenerate(root, plan)).toThrow(/nexus init/);
    expect(read(root, 'AGENTS.md')).toBe('# Mine\n');
  });
});

describe('docs generate under Claude Code', () => {
  it('is the same as with no harness named', () => {
    const root = vaultRepo(RULES);
    expect(expectedOutputs(root, 'claude-code')).toEqual(expectedOutputs(root));
    expect([...expectedOutputs(root).keys()].filter((k) => !k.startsWith('docs/'))).toEqual(['.claude/rules/nexus/explicit-staging.md', '.claude/rules/nexus/merge-loads.md']);
  });
});
