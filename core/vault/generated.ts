import { createHash } from 'node:crypto';

/** The first body line of every file nexus generates. The hash covers the file's text without this line. */
export const MARKER_RE = /^<!-- generated by nexus from (.+?) · sha256:([0-9a-f]{64}) · edit the source, not this file -->$/;

/** Text with its BOM dropped and line endings as LF: what hashes and comparisons see. */
export function lf(text: string): string {
  return text.replace(/^﻿/, '').replace(/\r\n?/g, '\n');
}

export function sha256(data: string | Uint8Array): string {
  return createHash('sha256').update(data).digest('hex');
}

export function markerLine(source: string, hash: string): string {
  return `<!-- generated by nexus from ${source} · sha256:${hash} · edit the source, not this file -->`;
}

/** The text with its marker: on the first line after the frontmatter, or the first line when there is none. */
export function withMarker(text: string, source: string): string {
  const body = lf(text);
  const lines = body.split('\n');
  const end = lines[0] === '---' ? lines.indexOf('---', 1) : -1;
  lines.splice(end + 1, 0, markerLine(source, sha256(body)));
  return lines.join('\n');
}

/**
 * The marker a file carries, with the hash of its text without that line (actual) and its 1-based line; null when none.
 * Only the first body line counts, where withMarker puts it, so a note quoting a marker isn't read as generated.
 */
export function readMarker(text: string): { source: string; hash: string; actual: string; line: number } | null {
  const lines = lf(text).split('\n');
  const end = lines[0] === '---' ? lines.indexOf('---', 1) : -1;
  const at = end + 1;
  const m = MARKER_RE.exec(lines[at] ?? '');
  if (!m?.[1] || !m[2]) return null;
  lines.splice(at, 1);
  return { source: m[1], hash: m[2], actual: sha256(lines.join('\n')), line: at + 1 };
}
